import { STATE_LABEL, formatClock, formatDuration, formatNumber, formatPercent } from "./evidence";
import type { Assessment } from "./evidence";
import { METRIC_ORDER } from "./scenario";

/**
 * Deterministic evidence report (Markdown). This is what "Generate AI Report" produces
 * in the demonstration: a template filled from the assessment. No model is called and
 * nothing leaves the browser.
 */
export const REPORT_GENERATOR = "pexisos-console deterministic template v1";

export function buildReport(a: Assessment): string {
  const { scenario, metrics, subsystems, checks, coverage, health, insight } = a;
  const out: string[] = [];
  out.push(`# Evidence report: ${scenario.deviceName}`);
  out.push("");
  out.push("> **Demonstration.** Generated by a deterministic template; no AI model was called.");
  out.push("> All readings are **synthetic** and do not describe any physical fan. This is not a diagnosis.");
  out.push("");
  out.push(`- Scenario: ${scenario.label} (\`${scenario.id}\`)`);
  out.push(`- Window: ${formatClock(scenario.windowStart)} to ${formatClock(scenario.asOf)} UTC, ${scenario.sampleIntervalMs / 1000} s sampling`);
  out.push(`- Generator: ${REPORT_GENERATOR}`);
  out.push("");
  out.push("## Observation");
  out.push("");
  out.push(`- **Observation:** ${insight.observation}`);
  out.push(`- **Status:** ${insight.status}`);
  out.push(`- **Evidence:** ${insight.evidence}`);
  out.push(`- **Confidence:** ${insight.confidence}`);
  out.push(`- **Note:** ${insight.note}`);
  out.push("");
  out.push("## Readings (latest, measured)");
  out.push("");
  out.push("| Metric | Latest | Expected | State | Evidence |");
  out.push("|---|---|---|---|---|");
  for (const id of METRIC_ORDER) {
    const series = scenario.series[id];
    const m = metrics[id];
    const latest = m.latest ? `${formatNumber(m.latest.value, series.decimals)} ${series.unit}` : "none";
    const expected = series.baseline !== undefined
      ? `baseline ${formatNumber(series.baseline, 0)} ${series.unit}`
      : `${formatNumber(series.normalRange.min, series.decimals)} to ${formatNumber(series.normalRange.max, series.decimals)} ${series.unit}`;
    const dev = m.deviation !== null ? ` (${formatPercent(m.deviation)})` : "";
    out.push(`| ${series.label} | ${latest}${dev} | ${expected} | ${STATE_LABEL[m.state]} | ${m.summary} |`);
  }
  out.push("");
  out.push(`## Subsystems (${health.nominal} of ${health.total} nominal)`);
  out.push("");
  out.push("| Subsystem | State | Basis | Confidence | Detail |");
  out.push("|---|---|---|---|---|");
  for (const s of subsystems) {
    out.push(`| ${s.label} | ${STATE_LABEL[s.state]} | ${s.basis} | ${s.confidence} | ${s.detail} |`);
  }
  out.push("");
  out.push(`## Evidence coverage (${coverage.evaluated} of ${coverage.total} checks evaluated)`);
  out.push("");
  for (const c of checks) out.push(`- [${c.evaluated ? "x" : " "}] ${c.label}${c.evaluated ? "" : `: ${c.reason}`}`);
  out.push("");
  out.push("## Limits");
  out.push("");
  out.push(`- A deviation becomes a suspicion only when it exceeds 10% for at least ${formatDuration(120_000)}.`);
  out.push("- Readings older than 30 s are stale and are not used to describe the present.");
  out.push("- Inferred statuses (Motor, Blades) are derived from other readings and can be wrong.");
  out.push("- The baseline is synthetic. Real baselines must come from the same device under similar conditions.");
  out.push("");
  return out.join("\n");
}
